CREATE OR REPLACE FUNCTION private.capture_passport_friend_product_event()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_subject uuid;
  v_action text;
  v_at timestamptz;
BEGIN
  IF TG_OP = 'DELETE' THEN
    v_subject := OLD.requested_by;
    v_at := coalesce(OLD.updated_at, timezone('utc', now()));
  ELSE
    v_subject := NEW.requested_by;
    v_at := coalesce(NEW.updated_at, timezone('utc', now()));
  END IF;
  v_action := CASE
    WHEN TG_OP = 'DELETE' THEN 'removed'
    WHEN TG_OP = 'INSERT' THEN 'requested'
    WHEN NEW.status = 'accepted' AND OLD.status IS DISTINCT FROM NEW.status THEN 'accepted'
    WHEN NEW.status = 'declined' AND OLD.status IS DISTINCT FROM NEW.status THEN 'declined'
    ELSE 'updated'
  END;
  PERFORM private.emit_passport_product_event(
    'passport_friend_action', v_subject, 'owner', 'database.passport_friendships',
    jsonb_build_object('action', v_action),
    CASE WHEN TG_OP = 'DELETE' THEN OLD.id ELSE NEW.id END::text
      || ':' || v_action || ':' || txid_current()::text,
    v_at
  );
  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION private.capture_passport_friend_product_event()
  FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS passport_friendships_capture_product_event ON public.passport_friendships;
CREATE TRIGGER passport_friendships_capture_product_event
AFTER INSERT OR UPDATE OF status OR DELETE ON public.passport_friendships
FOR EACH ROW EXECUTE FUNCTION private.capture_passport_friend_product_event();

