CREATE TABLE IF NOT EXISTS public.passport_product_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_name text NOT NULL,
  subject_user_id uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  actor_kind text NOT NULL DEFAULT 'anonymous',
  purpose text NOT NULL DEFAULT 'product_measurement',
  pii_classification text NOT NULL DEFAULT 'pseudonymous',
  source text NOT NULL,
  properties jsonb NOT NULL DEFAULT '{}'::jsonb,
  dedupe_key text NOT NULL UNIQUE,
  schema_version smallint NOT NULL DEFAULT 1,
  occurred_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  expires_at timestamptz NOT NULL DEFAULT (timezone('utc', now()) + interval '180 days'),
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  CONSTRAINT passport_product_events_name_allowed CHECK (event_name IN (
    'passport_created',
    'passport_publication_changed',
    'passport_onboarding_completed',
    'passport_game_added',
    'passport_five_games_reached',
    'passport_current_game_added',
    'passport_record_claimed',
    'passport_comparison_completed',
    'passport_card_generated',
    'passport_card_shared',
    'passport_public_viewed',
    'passport_cv_viewed',
    'passport_cv_downloaded',
    'passport_friend_action',
    'passport_replay_generated',
    'passport_replay_shared'
  )),
  CONSTRAINT passport_product_events_actor_allowed CHECK (
    actor_kind IN ('anonymous', 'owner', 'friend', 'member', 'system')
  ),
  CONSTRAINT passport_product_events_purpose_fixed CHECK (purpose = 'product_measurement'),
  CONSTRAINT passport_product_events_pii_allowed CHECK (
    pii_classification IN ('none', 'pseudonymous')
  ),
  CONSTRAINT passport_product_events_source_length CHECK (char_length(source) BETWEEN 2 AND 80),
  CONSTRAINT passport_product_events_properties_object CHECK (jsonb_typeof(properties) = 'object'),
  CONSTRAINT passport_product_events_dedupe_key_format CHECK (
    dedupe_key ~ '^[a-f0-9]{64}$'
  ),
  CONSTRAINT passport_product_events_retention_bounded CHECK (
    expires_at > occurred_at AND expires_at <= occurred_at + interval '181 days'
  )
);

CREATE INDEX IF NOT EXISTS passport_product_events_name_time_idx
  ON public.passport_product_events(event_name, occurred_at DESC);
CREATE INDEX IF NOT EXISTS passport_product_events_subject_time_idx
  ON public.passport_product_events(subject_user_id, occurred_at DESC)
  WHERE subject_user_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS passport_product_events_expiry_idx
  ON public.passport_product_events(expires_at);

ALTER TABLE public.passport_product_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.passport_product_events FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.passport_product_events_id_seq FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, DELETE ON TABLE public.passport_product_events TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.passport_product_events_id_seq TO service_role;

CREATE OR REPLACE FUNCTION private.emit_passport_product_event(
  p_event_name text,
  p_subject_user_id uuid,
  p_actor_kind text,
  p_source text,
  p_properties jsonb,
  p_dedupe_seed text,
  p_occurred_at timestamptz DEFAULT timezone('utc', now())
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  INSERT INTO public.passport_product_events(
    event_name,
    subject_user_id,
    actor_kind,
    source,
    properties,
    dedupe_key,
    occurred_at,
    expires_at
  )
  VALUES (
    p_event_name,
    p_subject_user_id,
    p_actor_kind,
    p_source,
    coalesce(p_properties, '{}'::jsonb),
    encode(extensions.digest(p_event_name || ':' || coalesce(p_subject_user_id::text, 'anonymous') || ':' || p_dedupe_seed, 'sha256'), 'hex'),
    p_occurred_at,
    p_occurred_at + interval '180 days'
  )
  ON CONFLICT (dedupe_key) DO NOTHING;
END;
$$;
REVOKE ALL ON FUNCTION private.emit_passport_product_event(text, uuid, text, text, jsonb, text, timestamptz)
  FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION private.capture_passport_profile_product_events()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    PERFORM private.emit_passport_product_event(
      'passport_created', NEW.user_id, 'owner', 'database.passport_profiles',
      jsonb_build_object('creation_source', 'owner'), NEW.user_id::text, NEW.created_at
    );
    RETURN NEW;
  END IF;

  IF NEW.publication_status IS DISTINCT FROM OLD.publication_status
    OR NEW.is_discoverable IS DISTINCT FROM OLD.is_discoverable
    OR NEW.default_visibility IS DISTINCT FROM OLD.default_visibility
  THEN
    PERFORM private.emit_passport_product_event(
      'passport_publication_changed', NEW.user_id, 'owner', 'database.passport_profiles',
      jsonb_build_object(
        'publication_status', NEW.publication_status,
        'discoverable', NEW.is_discoverable,
        'default_visibility', NEW.default_visibility
      ),
      NEW.user_id::text || ':' || NEW.public_version::text,
      NEW.updated_at
    );
  END IF;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION private.capture_passport_profile_product_events()
  FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS passport_profiles_capture_product_events ON public.passport_profiles;
CREATE TRIGGER passport_profiles_capture_product_events
AFTER INSERT OR UPDATE OF publication_status, is_discoverable, default_visibility
ON public.passport_profiles
FOR EACH ROW EXECUTE FUNCTION private.capture_passport_profile_product_events();

CREATE OR REPLACE FUNCTION private.capture_passport_game_product_events()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_game_count integer;
  v_current_game_count integer;
BEGIN
  IF TG_OP = 'INSERT' THEN
    PERFORM private.emit_passport_product_event(
      'passport_game_added', NEW.user_id, 'owner', 'database.passport_game_entries',
      jsonb_build_object(
        'play_status', NEW.play_status,
        'source_type', NEW.source_type,
        'visibility', NEW.visibility
      ),
      NEW.id::text,
      NEW.created_at
    );

    SELECT count(*)::integer INTO v_game_count
    FROM public.passport_game_entries
    WHERE user_id = NEW.user_id;

    IF v_game_count >= 5 THEN
      PERFORM private.emit_passport_product_event(
        'passport_five_games_reached', NEW.user_id, 'owner', 'database.passport_game_entries',
        jsonb_build_object('game_count_at_milestone', v_game_count),
        NEW.user_id::text,
        NEW.created_at
      );
    END IF;
  END IF;

  IF NEW.play_status = 'playing'
    AND (TG_OP = 'INSERT' OR OLD.play_status IS DISTINCT FROM NEW.play_status)
  THEN
    PERFORM private.emit_passport_product_event(
      'passport_current_game_added', NEW.user_id, 'owner', 'database.passport_game_entries',
      jsonb_build_object('source_type', NEW.source_type, 'visibility', NEW.visibility),
      NEW.id::text,
      coalesce(NEW.updated_at, NEW.created_at)
    );
  END IF;

  SELECT count(*)::integer INTO v_current_game_count
  FROM public.passport_game_entries
  WHERE user_id = NEW.user_id AND play_status = 'playing';
  IF v_game_count IS NULL THEN
    SELECT count(*)::integer INTO v_game_count
    FROM public.passport_game_entries
    WHERE user_id = NEW.user_id;
  END IF;
  IF v_game_count >= 5 AND v_current_game_count >= 1 THEN
    PERFORM private.emit_passport_product_event(
      'passport_onboarding_completed', NEW.user_id, 'owner', 'database.passport_game_entries',
      jsonb_build_object('completion_version', 'five_games_plus_current_v1'),
      NEW.user_id::text || ':five_games_plus_current_v1',
      coalesce(NEW.updated_at, NEW.created_at)
    );
  END IF;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION private.capture_passport_game_product_events()
  FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS passport_games_capture_product_events ON public.passport_game_entries;
CREATE TRIGGER passport_games_capture_product_events
AFTER INSERT OR UPDATE OF play_status ON public.passport_game_entries
FOR EACH ROW EXECUTE FUNCTION private.capture_passport_game_product_events();

