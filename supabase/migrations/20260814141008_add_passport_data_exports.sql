CREATE TABLE IF NOT EXISTS public.passport_data_exports (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'ready',
  format text NOT NULL DEFAULT 'json',
  schema_version text NOT NULL DEFAULT 'passport-export-v1',
  manifest jsonb NOT NULL DEFAULT '{}'::jsonb,
  payload jsonb,
  download_token_hash text,
  requested_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  ready_at timestamptz,
  expires_at timestamptz NOT NULL DEFAULT (timezone('utc', now()) + interval '24 hours'),
  downloaded_at timestamptz,
  download_count integer NOT NULL DEFAULT 0,
  failure_code text,
  CONSTRAINT passport_data_exports_status_allowed CHECK (
    status IN ('ready', 'failed', 'expired')
  ),
  CONSTRAINT passport_data_exports_format_allowed CHECK (format = 'json'),
  CONSTRAINT passport_data_exports_manifest_object CHECK (jsonb_typeof(manifest) = 'object'),
  CONSTRAINT passport_data_exports_payload_object CHECK (
    payload IS NULL OR jsonb_typeof(payload) = 'object'
  ),
  CONSTRAINT passport_data_exports_token_hash_format CHECK (
    download_token_hash IS NULL OR download_token_hash ~ '^[a-f0-9]{64}$'
  ),
  CONSTRAINT passport_data_exports_expiry_bounded CHECK (
    expires_at > requested_at AND expires_at <= requested_at + interval '24 hours 5 minutes'
  ),
  CONSTRAINT passport_data_exports_ready_complete CHECK (
    status <> 'ready'
    OR (payload IS NOT NULL AND download_token_hash IS NOT NULL AND ready_at IS NOT NULL)
  ),
  CONSTRAINT passport_data_exports_expired_scrubbed CHECK (
    status <> 'expired' OR (payload IS NULL AND download_token_hash IS NULL)
  ),
  CONSTRAINT passport_data_exports_download_count_non_negative CHECK (download_count >= 0)
);

CREATE TABLE IF NOT EXISTS public.passport_data_export_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  export_id uuid REFERENCES public.passport_data_exports(id) ON DELETE SET NULL,
  user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  action text NOT NULL,
  request_id_hash text,
  details jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT timezone('utc', now()),
  CONSTRAINT passport_data_export_audit_action_allowed CHECK (
    action IN ('requested', 'ready', 'downloaded', 'expired', 'failed')
  ),
  CONSTRAINT passport_data_export_audit_request_hash CHECK (
    request_id_hash IS NULL OR request_id_hash ~ '^[a-f0-9]{64}$'
  ),
  CONSTRAINT passport_data_export_audit_details_object CHECK (jsonb_typeof(details) = 'object')
);

CREATE INDEX IF NOT EXISTS passport_data_exports_user_requested_idx
  ON public.passport_data_exports(user_id, requested_at DESC);
CREATE INDEX IF NOT EXISTS passport_data_exports_expiry_idx
  ON public.passport_data_exports(expires_at)
  WHERE status = 'ready';
CREATE INDEX IF NOT EXISTS passport_data_export_audit_user_time_idx
  ON public.passport_data_export_audit(user_id, created_at DESC);

ALTER TABLE public.passport_data_exports ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.passport_data_export_audit ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.passport_data_exports, public.passport_data_export_audit
  FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.passport_data_export_audit_id_seq
  FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.passport_data_exports TO service_role;
GRANT SELECT, INSERT ON TABLE public.passport_data_export_audit TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.passport_data_export_audit_id_seq TO service_role;

CREATE OR REPLACE FUNCTION private.enforce_passport_data_export_rate_limit()
RETURNS trigger
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = ''
AS $$
DECLARE
  v_recent integer;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtextextended(NEW.user_id::text || ':passport-export', 0));
  SELECT count(*)::integer INTO v_recent
  FROM public.passport_data_exports
  WHERE user_id = NEW.user_id
    AND requested_at >= timezone('utc', now()) - interval '24 hours';
  IF v_recent >= 3 THEN
    RAISE EXCEPTION 'passport_export_rate_limited' USING ERRCODE = 'P0001';
  END IF;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION private.enforce_passport_data_export_rate_limit()
  FROM PUBLIC, anon, authenticated;

DROP TRIGGER IF EXISTS passport_data_exports_rate_limit ON public.passport_data_exports;
CREATE TRIGGER passport_data_exports_rate_limit
BEFORE INSERT ON public.passport_data_exports
FOR EACH ROW EXECUTE FUNCTION private.enforce_passport_data_export_rate_limit();
