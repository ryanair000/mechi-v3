CREATE OR REPLACE FUNCTION public.cleanup_passport_operational_data()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
  v_intents integer := 0;
  v_sync_runs integer := 0;
  v_api_events integer := 0;
  v_deliveries integer := 0;
  v_ecosystem_events integer := 0;
  v_product_events integer := 0;
  v_operation_runs integer := 0;
BEGIN
  DELETE FROM public.passport_connection_intents WHERE expires_at < timezone('utc', now()) - interval '7 days';
  GET DIAGNOSTICS v_intents = ROW_COUNT;
  DELETE FROM public.passport_provider_sync_runs WHERE started_at < timezone('utc', now()) - interval '180 days';
  GET DIAGNOSTICS v_sync_runs = ROW_COUNT;
  DELETE FROM public.passport_developer_api_events WHERE occurred_at < timezone('utc', now()) - interval '90 days';
  GET DIAGNOSTICS v_api_events = ROW_COUNT;
  DELETE FROM public.passport_webhook_deliveries WHERE status IN ('delivered', 'failed', 'cancelled') AND updated_at < timezone('utc', now()) - interval '30 days';
  GET DIAGNOSTICS v_deliveries = ROW_COUNT;
  DELETE FROM public.passport_ecosystem_events event
  WHERE event.created_at < timezone('utc', now()) - interval '180 days'
    AND NOT EXISTS (
      SELECT 1 FROM public.passport_webhook_deliveries delivery
      WHERE delivery.ecosystem_event_id = event.id AND delivery.status IN ('pending', 'retry', 'delivering')
    );
  GET DIAGNOSTICS v_ecosystem_events = ROW_COUNT;
  DELETE FROM public.passport_product_events WHERE expires_at < timezone('utc', now());
  GET DIAGNOSTICS v_product_events = ROW_COUNT;
  DELETE FROM public.passport_operation_runs WHERE started_at < timezone('utc', now()) - interval '180 days';
  GET DIAGNOSTICS v_operation_runs = ROW_COUNT;
  RETURN jsonb_build_object(
    'connection_intents', v_intents,
    'sync_runs', v_sync_runs,
    'developer_api_events', v_api_events,
    'webhook_deliveries', v_deliveries,
    'ecosystem_events', v_ecosystem_events,
    'product_events', v_product_events,
    'operation_runs', v_operation_runs
  );
END;
$$;
REVOKE ALL ON FUNCTION public.cleanup_passport_operational_data() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.cleanup_passport_operational_data() TO service_role;
